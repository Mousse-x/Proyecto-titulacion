def _load_env_file(path):
    """Carga backend/.env sin dependencias externas.

    Las variables ya definidas en el sistema tienen prioridad. El archivo está
    excluido de Git: allí se guardan las claves de los buscadores.
    """
    try:
        lines = path.read_text(encoding='utf-8-sig').splitlines()
    except FileNotFoundError:
        return
    for line in lines:
        line = line.strip()
        if not line or line.startswith('#') or '=' not in line:
            continue
        name, value = line.split('=', 1)
        name = name.strip().removeprefix('export ').strip()
        value = value.strip()
        if len(value) >= 2 and value[0] == value[-1] and value[0] in {'"', "'"}:
            value = value[1:-1]
        if name:
            os.environ.setdefault(name, value)


_load_env_file(BASE_DIR / '.env')


def _env_bool(name, default):
    value = os.environ.get(name)
    if value is None or value.strip() == '':
        return default
    return value.strip().lower() in {'1', 'true', 'yes', 'si', 'sí', 'on'}


def _env_list(name, default=()):
    value = os.environ.get(name)
    if value is None or value.strip() == '':
        return list(default)
    return [item.strip() for item in value.split(',') if item.strip()]


def _env_required(name):
    value = os.environ.get(name, '').strip()
    if not value:
        from django.core.exceptions import ImproperlyConfigured
        raise ImproperlyConfigured(
            f'Falta la variable {name} en backend/.env (ver backend/.env.production.example).'
        )
    return value


